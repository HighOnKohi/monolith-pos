-- 3a. Add to staff."Cashier_Shifts"
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'staff' AND table_name = 'Cashier_Shifts' AND table_type = 'BASE TABLE'
    ) THEN
        IF NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'staff' AND table_name = 'Cashier_Shifts' AND column_name = 'BUSINESS_DAY_ID'
        ) THEN
            ALTER TABLE staff."Cashier_Shifts"
                ADD COLUMN "BUSINESS_DAY_ID" BIGINT NULL REFERENCES staff."Business_Days"("BUSINESS_DAY_ID") ON DELETE SET NULL;
            CREATE INDEX IF NOT EXISTS idx_cashier_shifts_business_day_id
                ON staff."Cashier_Shifts" ("BUSINESS_DAY_ID");
        END IF;
    END IF;
END $$;

