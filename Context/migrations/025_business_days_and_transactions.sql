-- Function to start business day safely in schema staff
CREATE OR REPLACE FUNCTION staff.start_business_day(
    p_started_by TEXT,
    p_business_date DATE DEFAULT CURRENT_DATE
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_open_count INT;
    v_active_orders INT := 0;
    v_new_id BIGINT;
    v_row staff."Business_Days"%ROWTYPE;
BEGIN
    -- 1. Check if an open business day already exists
    SELECT COUNT(*) INTO v_open_count
    FROM staff."Business_Days"
    WHERE "STATUS" = 'OPEN';

    IF v_open_count > 0 THEN
        RAISE EXCEPTION 'A business day is already open. Please conclude the active day before starting a new one.';
    END IF;

    -- 2. Check if active orders exist in orders."Restaurant_Orders" base table
    BEGIN
        SELECT COUNT(*) INTO v_active_orders
        FROM orders."Restaurant_Orders"
        WHERE "ORDER_STATUS" IN ('REQUESTED', 'VERIFIED', 'PREPARING', 'READY', 'SERVED');
    EXCEPTION WHEN OTHERS THEN
        v_active_orders := 0;
    END;

    IF v_active_orders > 0 THEN
        RAISE EXCEPTION 'Cannot start business day: % active order(s) exist. All active orders must be completed or cancelled before opening a new day.', v_active_orders;
    END IF;

    -- 3. Insert new open Business Day
    INSERT INTO staff."Business_Days" (
        "BUSINESS_DATE",
        "STATUS",
        "STARTED_AT",
        "STARTED_BY"
    ) VALUES (
        COALESCE(p_business_date, CURRENT_DATE),
        'OPEN',
        NOW(),
        p_started_by
    )
    RETURNING * INTO v_row;

    RETURN to_jsonb(v_row);
END;
$$;

-- Function to end business day safely in schema staff
CREATE OR REPLACE FUNCTION staff.end_business_day(
    p_ended_by TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_active_day staff."Business_Days"%ROWTYPE;
    v_active_orders INT := 0;
    v_active_cashier_shifts INT := 0;
    v_active_service_shifts INT := 0;
    v_total_tx BIGINT := 0;
    v_total_rev DOUBLE PRECISION := 0;
    v_total_cust BIGINT := 0;
BEGIN
    -- 1. Retrieve the active business day
    SELECT * INTO v_active_day
    FROM staff."Business_Days"
    WHERE "STATUS" = 'OPEN'
    LIMIT 1;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No open business day found to conclude.';
    END IF;

    -- 2. Verify no active orders exist in orders."Restaurant_Orders"
    BEGIN
        SELECT COUNT(*) INTO v_active_orders
        FROM orders."Restaurant_Orders"
        WHERE "ORDER_STATUS" IN ('REQUESTED', 'VERIFIED', 'PREPARING', 'READY', 'SERVED');
    EXCEPTION WHEN OTHERS THEN
        v_active_orders := 0;
    END;

    IF v_active_orders > 0 THEN
        RAISE EXCEPTION 'Cannot end business day: % active order(s) still exist. Please settle or cancel all orders before concluding the day.', v_active_orders;
    END IF;

    -- 3. Verify no active cashier shifts exist
    BEGIN
        SELECT COUNT(*) INTO v_active_cashier_shifts
        FROM staff."Cashier_Shifts"
        WHERE "STATUS" = 'ACTIVE';
    EXCEPTION WHEN OTHERS THEN
        v_active_cashier_shifts := 0;
    END;

    IF v_active_cashier_shifts > 0 THEN
        RAISE EXCEPTION 'Cannot end business day: % active cashier shift(s) exist. All cashiers must conclude their shifts first.', v_active_cashier_shifts;
    END IF;

    -- 4. Verify no active service shifts exist
    BEGIN
        SELECT COUNT(*) INTO v_active_service_shifts
        FROM staff."Service_Shifts"
        WHERE "STATUS" = 'ACTIVE';
    EXCEPTION WHEN OTHERS THEN
        v_active_service_shifts := 0;
    END;

    IF v_active_service_shifts > 0 THEN
        RAISE EXCEPTION 'Cannot end business day: % active service shift(s) exist. All floor staff must conclude their shifts first.', v_active_service_shifts;
    END IF;

    -- 5. Calculate daily metrics directly from system_history."Completed_Orders" during this business day
    BEGIN
        SELECT
            COUNT(*),
            COALESCE(SUM("TOTAL_BILL"), 0),
            COALESCE(SUM("GUEST_COUNT"), 0)
        INTO
            v_total_tx,
            v_total_rev,
            v_total_cust
        FROM system_history."Completed_Orders"
        WHERE ("BUSINESS_DAY_ID" = v_active_day."BUSINESS_DAY_ID"
               OR ("COMPLETED_AT" >= v_active_day."STARTED_AT" AND v_active_day."BUSINESS_DAY_ID" IS NOT NULL));
    EXCEPTION WHEN OTHERS THEN
        NULL;
    END;

    -- 6. Update the business day to CLOSED
    UPDATE staff."Business_Days"
    SET "STATUS" = 'CLOSED',
        "ENDED_AT" = NOW(),
        "ENDED_BY" = p_ended_by,
        "TOTAL_TRANSACTIONS" = v_total_tx,
        "TOTAL_REVENUE" = v_total_rev,
        "TOTAL_CUSTOMERS_SERVED" = v_total_cust
    WHERE "BUSINESS_DAY_ID" = v_active_day."BUSINESS_DAY_ID"
    RETURNING * INTO v_active_day;

    RETURN to_jsonb(v_active_day);
END;
$$;

