-- 3d. Add Attribution to system_history."Completed_Orders" (Base Table)
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'system_history' AND table_name = 'Completed_Orders' AND table_type = 'BASE TABLE'
    ) THEN
        -- Add columns if not present
        ALTER TABLE system_history."Completed_Orders"
            ADD COLUMN IF NOT EXISTS "BUSINESS_DAY_ID" BIGINT NULL,
            ADD COLUMN IF NOT EXISTS "SHIFT_ID" BIGINT NULL,
            ADD COLUMN IF NOT EXISTS "STAFF_ID" BIGINT NULL,
            ADD COLUMN IF NOT EXISTS "CASHIER_NAME" TEXT NULL;

        -- Foreign Key to Business_Days
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint WHERE conname = 'completed_orders_business_day_id_fkey'
        ) THEN
            ALTER TABLE system_history."Completed_Orders"
                ADD CONSTRAINT completed_orders_business_day_id_fkey
                FOREIGN KEY ("BUSINESS_DAY_ID") REFERENCES staff."Business_Days"("BUSINESS_DAY_ID") ON DELETE SET NULL;
        END IF;

        -- Drop restrictive shift_id foreign key because Completed_Orders records orders from Cashier_Shifts or Service_Shifts
        ALTER TABLE system_history."Completed_Orders"
            DROP CONSTRAINT IF EXISTS completed_orders_shift_id_fkey;

        -- Foreign Key to Staff_Codes
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint WHERE conname = 'completed_orders_staff_id_fkey'
        ) THEN
            ALTER TABLE system_history."Completed_Orders"
                ADD CONSTRAINT completed_orders_staff_id_fkey
                FOREIGN KEY ("STAFF_ID") REFERENCES staff."Staff_Codes"("CODE_ID") ON DELETE SET NULL;
        END IF;

        -- Performance Indexes
        CREATE INDEX IF NOT EXISTS idx_completed_orders_business_day_id
            ON system_history."Completed_Orders" ("BUSINESS_DAY_ID");

        CREATE INDEX IF NOT EXISTS idx_completed_orders_staff_id
            ON system_history."Completed_Orders" ("STAFF_ID");

        CREATE INDEX IF NOT EXISTS idx_completed_orders_shift_id
            ON system_history."Completed_Orders" ("SHIFT_ID");
    END IF;
END $$;

