    p_started_by TEXT,
    p_business_date DATE DEFAULT CURRENT_DATE
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN staff.start_business_day(p_started_by, p_business_date);
END;
$$;

