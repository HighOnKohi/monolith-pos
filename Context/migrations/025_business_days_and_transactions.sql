-- ==============================================================================
-- Migration 025: Business Day Management, Cashier Transactions, and Daily Summary
-- Schemas:
--   - staff."Business_Days" (Base Table)
--   - staff."Cashier_Shifts", staff."Service_Shifts", staff."Audit_Logs"
--   - system_history."Completed_Orders" (Base Table)
--   - orders."Restaurant_Orders" (Base Table)
--   - Public Views with security_invoker = on for PostgREST access
--
-- Purpose:
--   1. Establishes the persistent Business Day table (staff."Business_Days")
--      controlling whether POS interfaces are permitted to accept transactions.
--   2. Enforces that at most ONE business day may be active ('OPEN') at any time.
--   3. Associates Cashier Shifts, Service Shifts, Audit Logs, and Completed Orders
--      with the active BUSINESS_DAY_ID via foreign keys on base tables in domain schemas.
--   4. Provides race-condition-free database functions for Start Day and End Day,
--      preventing Start/End Day if unresolved active orders exist in orders."Restaurant_Orders".
--   5. Tracks per-cashier transaction attribution and provides daily summary aggregates
--      directly from system_history."Completed_Orders".
--
-- Instructions:
--   Open Supabase Dashboard -> SQL Editor -> New Query -> Paste & Run
-- ==============================================================================

-- Step 0: Ensure schemas exist and permissions are granted
CREATE SCHEMA IF NOT EXISTS staff;
CREATE SCHEMA IF NOT EXISTS system_history;
CREATE SCHEMA IF NOT EXISTS orders;

GRANT USAGE ON SCHEMA staff TO anon, authenticated, service_role;
GRANT USAGE ON SCHEMA system_history TO anon, authenticated, service_role;
GRANT USAGE ON SCHEMA orders TO anon, authenticated, service_role;

-- ------------------------------------------------------------------------------
-- Step 1: Create staff."Business_Days" Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS staff."Business_Days" (
    "BUSINESS_DAY_ID"        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "BUSINESS_DATE"          DATE NOT NULL DEFAULT CURRENT_DATE,
    "STATUS"                 TEXT NOT NULL DEFAULT 'OPEN',
    "STARTED_AT"             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    "STARTED_BY"             TEXT NULL,
    "ENDED_AT"               TIMESTAMP WITH TIME ZONE NULL,
    "ENDED_BY"               TEXT NULL,
    "TOTAL_TRANSACTIONS"     BIGINT NOT NULL DEFAULT 0,
    "TOTAL_REVENUE"          DOUBLE PRECISION NOT NULL DEFAULT 0,
    "TOTAL_CUSTOMERS_SERVED" BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT "Business_Days_pkey" PRIMARY KEY ("BUSINESS_DAY_ID"),
    CONSTRAINT "business_days_status_check" CHECK (
        "STATUS" = ANY (ARRAY['OPEN'::text, 'CLOSED'::text])
    )
);

-- Enforce ONLY ONE open business day at any time
CREATE UNIQUE INDEX IF NOT EXISTS idx_one_open_business_day
    ON staff."Business_Days" ("STATUS")
    WHERE ("STATUS" = 'OPEN');

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_business_days_date
    ON staff."Business_Days" ("BUSINESS_DATE" DESC);

CREATE INDEX IF NOT EXISTS idx_business_days_started_at
    ON staff."Business_Days" ("STARTED_AT" DESC);

-- ------------------------------------------------------------------------------
-- Step 2: Create Public View (with security_invoker = on) for PostgREST Access
-- ------------------------------------------------------------------------------
CREATE OR REPLACE VIEW public."Business_Days"
    WITH (security_invoker = on) AS
    SELECT * FROM staff."Business_Days";

