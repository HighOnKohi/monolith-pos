CREATE TABLE IF NOT EXISTS tables."Restaurant_Tables" (
    "TABLE_ID"             bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "TABLE_NUM"            bigint NOT NULL DEFAULT 0,
    "STATUS"               text NULL,
    "GUEST_CAPACITY"       bigint NULL DEFAULT 0,
    "CURRENT_GUEST_COUNT"  bigint NULL DEFAULT 0,
    "RESERVED_SINCE"       timestamp without time zone NULL,
    "BILL_OUT_REQUESTED"   boolean NULL DEFAULT false,
    "MERGE_GROUP_ID"       bigint NULL DEFAULT NULL,
    "RESERVATION_NAME"     text NULL DEFAULT NULL,
    "RESERVATION_PAX"      bigint NULL DEFAULT NULL,
    "RESERVATION_NOTES"    text NULL DEFAULT NULL,
    "IS_MERGE_MEMBER"      boolean NULL DEFAULT false,
    "IS_MERGE_CAPTAIN"     boolean NULL DEFAULT false,
    -- From migration 018 (newer than CSV):
    "LAYOUT_X"             integer NULL DEFAULT NULL,
    "LAYOUT_Y"             integer NULL DEFAULT NULL,
    CONSTRAINT "Restaurant_Tables_pkey" PRIMARY KEY ("TABLE_ID"),
    CONSTRAINT restaurant_tables_status_check CHECK (
        "STATUS" = ANY (ARRAY[
            'AVAILABLE'::text, 'RESERVED'::text, 'OCCUPIED'::text,
            'HAS_REQUEST'::text, 'UNAVAILABLE'::text
        ])
    )
);

-- Self-referencing FK for merged tables
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'restaurant_tables_merge_group_fkey') THEN
        ALTER TABLE tables."Restaurant_Tables"
        ADD CONSTRAINT restaurant_tables_merge_group_fkey
        FOREIGN KEY ("MERGE_GROUP_ID") REFERENCES tables."Restaurant_Tables" ("TABLE_ID") ON DELETE SET NULL;
    END IF;
END $$;

