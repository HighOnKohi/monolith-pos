DECLARE
    t RECORD;
BEGIN
    FOR t IN
        SELECT schemaname, tablename
        FROM pg_tables
        WHERE schemaname IN ('menu','orders','tables','staff','tickets','advance','analytics','events')
    LOOP
        EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', t.schemaname, t.tablename);
        EXECUTE format(
            'CREATE POLICY "Allow all" ON %I.%I FOR ALL USING (true) WITH CHECK (true)',
            t.schemaname, t.tablename
        );
    END LOOP;
END $$;


