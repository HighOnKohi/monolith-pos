CREATE TABLE IF NOT EXISTS orders."Restaurant_Orders" (
    "ORDER_ID"        bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "TABLE_ID"        bigint NOT NULL REFERENCES tables."Restaurant_Tables"("TABLE_ID") ON DELETE CASCADE,
    "REQUESTED_FROM"  text NULL DEFAULT 'None'::text,
    "ORDER_TYPE"      text NULL DEFAULT 'Dine-in'::text,
    "ORDER_STATUS"    text NULL DEFAULT 'Pending'::text,
    "SUBTOTAL_BILL"   double precision NULL DEFAULT 0,
    "TOTAL_BILL"      double precision NULL DEFAULT 0,
    "TIME"            timestamp without time zone NULL,
    "KITCHEN_NOTE"    text NULL,
    "SERVER_NOTE"     text NULL,
    "GUEST_COUNT"     integer NULL DEFAULT 1,
    "READY_AT"        timestamp without time zone NULL,
    "SERVED_AT"       timestamp without time zone NULL,
    "COMPLETED_AT"    timestamp without time zone NULL,
    "PAYMENT_METHOD"  text NULL DEFAULT 'CASH'::text,
    CONSTRAINT "Restaurant_Orders_pkey" PRIMARY KEY ("ORDER_ID"),
    CONSTRAINT "Restaurant_Orders_ORDER_ID_key" UNIQUE ("ORDER_ID"),
    CONSTRAINT restaurant_orders_requested_from_check CHECK (
        "REQUESTED_FROM" = ANY (ARRAY['Cashier'::text, 'Customer'::text])
    ),
    CONSTRAINT restaurant_orders_order_type_check CHECK (
        "ORDER_TYPE" = ANY (ARRAY['DINE-IN'::text, 'TAKEOUT'::text])
    ),
    CONSTRAINT restaurant_orders_order_status_check CHECK (
        "ORDER_STATUS" = ANY (ARRAY[
            'REQUESTED'::text, 'VERIFIED'::text, 'PREPARING'::text,
            'READY'::text, 'SERVED'::text, 'CANCELLED'::text, 'COMPLETED'::text
        ])
    )
);

ALTER TABLE orders."Restaurant_Orders" REPLICA IDENTITY FULL;

CREATE TABLE IF NOT EXISTS orders."Order_Items" (
    "ORDER_ITEM_ID"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
