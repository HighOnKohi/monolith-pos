-- Cross-references: Events <-> Layout Presets
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'fk_restaurant_events_preset') THEN
        ALTER TABLE events."Restaurant_Events"
            ADD CONSTRAINT fk_restaurant_events_preset
            FOREIGN KEY ("PRESET_ID") REFERENCES tables."Table_Layout_Presets"("PRESET_ID") ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'fk_table_layout_presets_event') THEN
        ALTER TABLE tables."Table_Layout_Presets"
            ADD CONSTRAINT fk_table_layout_presets_event
            FOREIGN KEY ("EVENT_ID") REFERENCES events."Restaurant_Events"("EVENT_ID") ON DELETE SET NULL;
    END IF;
END $$;


